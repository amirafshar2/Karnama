namespace Karnama.Application.Abstractions;

/// <summary>A small live message: what changed (kind + id + field names) and its cursor — never the whole object.</summary>
public sealed record ChangeDelta(long Seq, string Kind, Guid Id, IReadOnlyList<string> Fields, Guid? ClientId, Guid? AssigneeId, Guid? PreviousAssigneeId);

/// <summary>Records changes in the same transaction as the data (so the cursor never misses one) and broadcasts after commit.</summary>
public interface IChangeFeed
{
    void Record(string kind, Guid id, Guid? clientId, Guid? assigneeId, Guid? previousAssigneeId, params string[] fields);
    Task PublishAsync(CancellationToken ct);
}

/// <summary>Private file storage (outside the web root). Keys are generated by the server, never taken from a client.</summary>
public interface IFileStore
{
    Task AppendAsync(string key, long offset, Stream data, long length, CancellationToken ct);
    Task<byte[]> ReadHeadAsync(string key, int count, CancellationToken ct);
    Stream OpenRead(string key);
    Task DeleteAsync(string key, CancellationToken ct);
}
