internal static class JsonColumn
{
    private static readonly JsonSerializerOptions Options = new(JsonSerializerDefaults.Web);

    /// <summary>Maps any serializable value to a jsonb column with value-based change tracking.</summary>
    public static PropertyBuilder<T> AsJson<T>(this PropertyBuilder<T> p) where T : class =>
        p.HasColumnType("jsonb").HasConversion(
            new ValueConverter<T, string>(v => JsonSerializer.Serialize(v, Options), v => JsonSerializer.Deserialize<T>(v, Options)!),
            new ValueComparer<T>(
                (a, b) => JsonSerializer.Serialize(a, Options) == JsonSerializer.Serialize(b, Options),
                v => JsonSerializer.Serialize(v, Options).GetHashCode(StringComparison.Ordinal),
                v => JsonSerializer.Deserialize<T>(JsonSerializer.Serialize(v, Options), Options)!));

    public static PropertyBuilder<LocalizedText> AsLocalized(this PropertyBuilder<LocalizedText> p) =>
        p.HasColumnType("jsonb").HasConversion(LocalizedTextConversion.Converter, LocalizedTextConversion.Comparer);
}

/// <summary>JSON shape of a localized list (features) — LocalizedText isn't directly serializable.</summary>
internal static class LocalizedListConversion
{
    private static readonly JsonSerializerOptions Options = new(JsonSerializerDefaults.Web);

    public static PropertyBuilder<List<LocalizedText>> AsLocalizedList(this PropertyBuilder<List<LocalizedText>> p) =>
        p.HasColumnType("jsonb").HasConversion(
            new ValueConverter<List<LocalizedText>, string>(
                v => JsonSerializer.Serialize(v.Select(x => x.Values).ToList(), Options),
                v => (JsonSerializer.Deserialize<List<Dictionary<string, string>>>(v, Options) ?? new()).Select(d => new LocalizedText(d)).ToList()),
            new ValueComparer<List<LocalizedText>>(
                (a, b) => a!.Count == b!.Count && a.Zip(b).All(z => z.First.Equals(z.Second)),
                v => v.Aggregate(0, (h, x) => HashCode.Combine(h, x.GetHashCode())),
                v => v.Select(x => new LocalizedText(x.Values)).ToList()));
}

